/** Languages not covered by ISO 639 display names. */
const EXTRA_LANGUAGES = ['Libras (Língua Brasileira de Sinais)'];

function capitalize(value: string): string {
  return value.charAt(0).toLocaleUpperCase('pt-BR') + value.slice(1);
}

function buildOptions(
  type: 'region' | 'language',
  codes: string[],
  extra: string[] = [],
): LocaleOption[] {
  let display: Intl.DisplayNames | null = null;
  try {
    display = new Intl.DisplayNames(['pt-BR'], { type, fallback: 'none' });
  } catch {
    display = null;
  }

  const names = new Set<string>(extra);
  for (const code of codes) {
    const name = display?.of(code);
    if (name) names.add(capitalize(name));
  }

  return [...names]
    .sort((a, b) => a.localeCompare(b, 'pt-BR'))
    .map((name) => ({ value: name, label: name }));
}

let countryOptions: LocaleOption[] | null = null;
let languageOptions: LocaleOption[] | null = null;

/** Country names in pt-BR (the stored value is the name itself). */
export function getCountryOptions(): LocaleOption[] {
  countryOptions ??= buildOptions('region', COUNTRY_CODES);
  return countryOptions;
}

/** Language names in pt-BR (the stored value is the name itself). */
export function getLanguageOptions(): LocaleOption[] {
  languageOptions ??= buildOptions('language', LANGUAGE_CODES, EXTRA_LANGUAGES);
  return languageOptions;
}

/** Ensures a previously stored value outside the list is still selectable/visible. */
export function withCurrentValue(
  options: LocaleOption[],
  current: string | undefined,
): LocaleOption[] {
  if (!current || options.some((option) => option.value === current)) return options;
  return [{ value: current, label: current }, ...options];
}
